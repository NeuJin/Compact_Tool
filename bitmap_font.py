def _validate():
    from page_format import ALPHABET

    missing = [c for c in ALPHABET if c not in GLYPHS]
    if missing:
        raise ValueError(f"bitmap_font missing glyphs for: {missing}")
    for ch, rows in GLYPHS.items():
        if len(rows) != FONT_H:
            raise ValueError(f"glyph {ch!r} has {len(rows)} rows, expected {FONT_H}")
        for r in rows:
            if len(r) != FONT_W:
                raise ValueError(f"glyph {ch!r} row {r!r} has width {len(r)}, expected {FONT_W}")
            if any(c not in "#." for c in r):
                raise ValueError(f"glyph {ch!r} row {r!r} has chars other than '#'/'.'")


_validate()
